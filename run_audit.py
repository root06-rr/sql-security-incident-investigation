#!/usr/bin/env python3
"""Run the repository SQL exercises using Python built-in SQLite."""

from pathlib import Path
import sqlite3
import sys

ROOT = Path(__file__).resolve().parent
SETUP_FILE = ROOT / "database" / "setup_database.sql"
INVESTIGATIONS_DIR = ROOT / "investigations"
REPORT_FILE = ROOT / "reports" / "audit_findings_report.md"

def remove_sqlite_incompatible_setup_lines(sql_text):
    """Skip MySQL database creation and selection commands."""
    kept_lines = []
    for line in sql_text.splitlines():
        command = line.strip().rstrip(';').upper()
        if command.startswith("CREATE DATABASE "):
            continue
        if command.startswith("USE "):
            continue
        kept_lines.append(line)
    return "\n".join(kept_lines)

def split_sql_statements(sql_text):
    """Split at complete SQL statement boundaries."""
    statements = []
    buffer = ""
    for line in sql_text.splitlines():
        buffer += line + "\n"
        if sqlite3.complete_statement(buffer):
            statement = buffer.strip()
            if statement:
                statements.append(statement)
            buffer = ""
    if buffer.strip():
        raise ValueError("SQL file ends with an incomplete statement.")
    return statements

def format_table(columns, rows):
    if not columns:
        return "(Statement completed. No rows returned.)"
    values = [[('NULL' if value is None else str(value)) for value in row] for row in rows]
    widths = [max([len(str(columns[i]))] + [len(row[i]) for row in values]) for i in range(len(columns))]
    def row_text(row):
        return "| " + " | ".join(str(value).ljust(widths[i]) for i, value in enumerate(row)) + " |"
    divider = "|-" + "-|-".join("-" * width for width in widths) + "-|"
    return "\n".join([row_text(columns), divider] + [row_text(row) for row in values])

def execute_file(connection, sql_file):
    sql_text = sql_file.read_text(encoding="utf-8")
    if sql_file == SETUP_FILE:
        sql_text = remove_sqlite_incompatible_setup_lines(sql_text)
    results = []
    for number, statement in enumerate(split_sql_statements(sql_text), start=1):
        cursor = connection.execute(statement)
        if cursor.description:
            columns = [item[0] for item in cursor.description]
            rows = cursor.fetchall()
            results.append((number, statement, columns, rows))
        else:
            results.append((number, statement, [], []))
    return results

def main():
    if not SETUP_FILE.is_file():
        print(f"Setup SQL file not found: {SETUP_FILE}", file=sys.stderr)
        return 1
    investigation_files = sorted(INVESTIGATIONS_DIR.glob("*/investigation.sql"))
    if not investigation_files:
        print(f"No investigation SQL files found under: {INVESTIGATIONS_DIR}", file=sys.stderr)
        return 1
    report = [
        "# SQL Audit Findings Report",
        "",
        "Generated by run_audit.py from the setup SQL and investigation scripts.",
        "",
        "The runner uses an in-memory SQLite database. MySQL CREATE DATABASE and USE statements are skipped because SQLite does not use them. Table definitions, sample inserts, and investigation statements are executed against SQLite.",
        "",
        "These results use simulated sample records. They do not represent a real security incident.",
        ""
    ]
    try:
        with sqlite3.connect(":memory:") as connection:
            for sql_file in [SETUP_FILE] + investigation_files:
                relative = sql_file.relative_to(ROOT).as_posix()
                print("\n" + "=" * 78 + "\n" + relative + "\n" + "=" * 78)
                report.extend([f"## {relative}", ""])
                sections = execute_file(connection, sql_file)
                for number, statement, columns, rows in sections:
                    print(f"\nStatement {number}:")
                    table = format_table(columns, rows)
                    print(table)
                    report.extend([f"### Statement {number}", "", "```sql", statement, "```", "", table, ""])
                    if columns:
                        report.extend([f"Rows returned: {len(rows)}", ""])
        REPORT_FILE.parent.mkdir(parents=True, exist_ok=True)
        REPORT_FILE.write_text("\n".join(report).rstrip() + "\n", encoding="utf-8")
        print(f"\nReport written to: {REPORT_FILE.relative_to(ROOT)}")
        return 0
    except (sqlite3.Error, OSError, ValueError) as error:
        print(f"Audit failed: {error}", file=sys.stderr)
        return 1

if __name__ == "__main__":
    raise SystemExit(main())
